/** Body parts a word can open with, for the rule category below. */
const BODY_STARTS = ['ARM', 'HAND', 'LEG', 'SHIN', 'EAR', 'HIP', 'KNEE', 'LIP', 'CHIN', 'TOE', 'NOSE', 'HEEL', 'BACK', 'FOOT', 'HEAD', 'NECK', 'CHEST', 'EYE', 'JAW', 'LUNG', 'LIVER', 'SKIN'];

/** Numbers hidden inside a longer word. */
const HIDDEN_NUMBERS = ['ONE', 'TWO', 'SIX', 'TEN', 'NINE', 'EIGHT'];

const RULES: RuleCategory[] = [
  {
    tier: 4,
    name: 'Starts with a body part',
    // The word has to carry on past the body part — `ARM` itself is not
    // "starting with" anything — and a plural (`EARS`, `EYES`) is the body part
    // rather than a word that happens to open with one.
    test: (word) =>
      BODY_STARTS.some(
        (part) => word.startsWith(part) && word.length > part.length && word !== `${part}S`,
      ),
    seed: 'ARMADA HANDLE LEGEND SHINDIG EARNEST HIPSTER KNEEL LIPSTICK CHINCHILLA TOENAIL HANDSOME ARMOR',
  },
  {
    tier: 4,
    name: 'Hidden numbers',
    test: (word) => HIDDEN_NUMBERS.some((n) => word !== n && word.includes(n)),
    seed: 'OFTEN CANINE LONELY WEIGHT FREIGHT PHONE MONEY HONEY KITTEN TENDON ATTENTION',
  },
];

