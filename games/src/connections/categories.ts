function build(): Category[] {
  const out: Category[] = [];

  for (const line of LISTS.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const [tier, name, words, family] = trimmed.split('|');
    out.push({
      id: out.length,
      name: name as string,
      tier: Number(tier) as Category['tier'],
      words: dedupe((words as string).split(/\s+/)),
      family: family ?? null,
    });
  }

  // Rule categories are resolved against the whole vocabulary, so they go last
  // and see every list above.
  const vocabulary = new Set(out.flatMap((category) => category.words));
  for (const rule of RULES) {
    const seed = rule.seed.split(/\s+/);
    for (const word of seed) vocabulary.add(word);
    const words = [...vocabulary].filter(rule.test).sort();
    out.push({ id: out.length, name: rule.name, tier: rule.tier, words, family: null });
  }

  return out;
}

function dedupe(words: string[]): string[] {
  return [...new Set(words)];
}

export const CATEGORIES: readonly Category[] = build();

/** Every category each word belongs to. The one index the solver needs. */
export const MEMBERSHIP: ReadonlyMap<string, readonly number[]> = (() => {
  const map = new Map<string, number[]>();
  for (const category of CATEGORIES) {
    for (const word of category.words) {
      const list = map.get(word);
      if (list) list.push(category.id);
      else map.set(word, [category.id]);
    }
  }
  return map;
})();
