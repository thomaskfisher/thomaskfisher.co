/**
 * The category bank.
 *
 * Every level is four of these, four words from each. Nothing else in the game
 * knows what a word means, so **this file is the whole of what the solver can
 * see** — a word that plainly belongs to a category but is missing from its
 * list is invisible to the uniqueness check, and that is the one way a board
 * can ship with two answers. Lists are therefore written to be complete for the
 * short, common words, which are the ones that turn up in other lists.
 *
 * Overlaps are the point, not an accident. `BASS` is a fish and an instrument,
 * `EAGLE` is a bird, a golf score and a yoga pose, `PYTHON` is a snake and a
 * programming language. The generator leans on exactly these to plant red
 * herrings, and the solver is what keeps them fair: a board ships only if the
 * sixteen words split into four groups one way and one way only, across every
 * category here, not just the four that were chosen.
 *
 * Tiers run 1 (plain membership: Fish) to 4 (wordplay: FIRE ___). They decide
 * the colour of a solved group — yellow, green, blue, purple, easiest first —
 * and weight how readily the naive player in `solve.ts` spots a group.
 *
 * Format: `tier|Name|WORD WORD WORD`, and an optional fourth field naming a
 * family. Two categories in one family never share a board, for pairs that are
 * the same idea twice (Shakespeare's plays and his characters) where splitting
 * them would be a coin toss rather than a deduction.
 */

export interface Category {
  id: number;
  name: string;
  tier: 1 | 2 | 3 | 4;
  words: readonly string[];
  family: string | null;
}

/**
 * Categories whose membership is a spelling rule rather than a list.
 *
 * A list cannot be complete for "contains a hidden number" — `MONEY`, `KITTEN`
 * and `STONE` all qualify and they come from three unrelated lists — so these
 * are tested against every word in the bank instead, and `seed` only supplies
 * members that no other category happens to contain.
 */
interface RuleCategory {
  tier: 4;
  name: string;
  test: (word: string) => boolean;
  seed: string;
}

